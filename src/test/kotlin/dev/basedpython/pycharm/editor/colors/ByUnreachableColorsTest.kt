package dev.basedpython.pycharm.editor.colors

import com.intellij.openapi.editor.colors.EditorColorsManager
import com.intellij.openapi.editor.colors.EditorColorsScheme
import com.intellij.openapi.editor.colors.impl.EditorColorsSchemeImpl
import com.intellij.openapi.util.JDOMUtil
import com.intellij.testFramework.junit5.fixture.TestFixtures
import dev.basedpython.pycharm.testFramework.codeInsightFixture
import dev.basedpython.pycharm.testFramework.onEdt
import org.junit.jupiter.api.Assertions.assertEquals
import org.junit.jupiter.api.Assertions.assertTrue
import org.junit.jupiter.api.Test
import java.io.File
import java.nio.file.Files
import java.nio.file.Paths

/**
 * The unreachable variants' colours shipped for each bundled scheme (a file per scheme in
 * `colorSchemes/unreachable`, registered as `additionalTextAttributes`) are what
 * [ByUnreachableColors.defaultsFor] computes from that scheme as the platform under test has it.
 *
 * So a platform whose schemes change fails here rather than shipping fades of colours the schemes
 * no longer have. Running this class with `-Pbasedpython.regenerateUnreachableColors` writes the
 * files afresh from the schemes instead; commit what changed.
 */
@TestFixtures
class ByUnreachableColorsTest {

    private val fixture by codeInsightFixture()

    /** Each scheme a file is shipped for: its name, the file, and where the scheme is read from. */
    private data class Shipped(val scheme: String, val file: String, val source: String?, val parent: String?)

    private val shipped = listOf(
        Shipped("Default", "Default.xml", null, null),
        Shipped("Darcula", "Darcula.xml", null, null),
        Shipped("Light", "Light.xml", "/themes/expUI/expUI_lightScheme.xml", "Default"),
        Shipped("Dark", "Dark.xml", "/themes/expUI/expUI_darkScheme.xml", "Darcula"),
        Shipped("Darcula Contrast", "DarculaContrast.xml", "/themes/expUI/expUI_darculaContrastScheme.xml", "Darcula"),
        Shipped("Islands Dark", "IslandsDark.xml", "/themes/islands/IslandSchemeDark.xml", "Darcula"),
        Shipped("basedpython dark", "BasedPythonDark.xml", "/colorSchemes/BasedPythonDark.xml", "Darcula"),
        Shipped("basedpython Light", "BasedPythonLight.xml", "/colorSchemes/BasedPythonLight.xml", "Default"),
    )

    private val resources = Paths.get("src/main/resources/colorSchemes/unreachable")

    private fun scheme(entry: Shipped): EditorColorsScheme {
        val manager = EditorColorsManager.getInstance()
        if (entry.source == null) return manager.getScheme(entry.scheme)!!
        val parent = manager.getScheme(entry.parent!!)!!
        val element = JDOMUtil.load(javaClass.getResourceAsStream(entry.source)!!)
        return EditorColorsSchemeImpl(parent).apply { readExternal(element) }
    }

    /** The file [ByUnreachableColors.defaultsFor] makes for [scheme], as `additionalTextAttributes` reads it. */
    private fun render(scheme: EditorColorsScheme): String = buildString {
        append("<?xml version='1.0'?>\n")
        append("<!-- Generated by ByUnreachableColorsTest from the scheme as the platform has it; do not edit. -->\n")
        append("<list>\n")
        for ((key, attributes) in ByUnreachableColors.defaultsFor(scheme).entries.sortedBy { it.key.externalName }) {
            append("  <option name=\"${key.externalName}\">\n    <value>\n")
            append("      <option name=\"FOREGROUND\" value=\"${"%06x".format(attributes.foregroundColor.rgb and 0xffffff)}\"/>\n")
            if (attributes.fontType != 0) append("      <option name=\"FONT_TYPE\" value=\"${attributes.fontType}\"/>\n")
            append("    </value>\n  </option>\n")
        }
        append("</list>\n")
    }

    @Test
    fun `the shipped unreachable colours are the bundled schemes' colours, faded`() = onEdt {
        val regenerate = System.getProperty("basedpython.regenerateUnreachableColors") == "true"
        val stale = mutableListOf<String>()
        for (entry in shipped) {
            val expected = render(scheme(entry))
            val file = resources.resolve(entry.file)
            if (regenerate) {
                Files.createDirectories(resources)
                Files.writeString(file, expected)
            } else if (!Files.exists(file) || Files.readString(file) != expected) {
                stale += entry.file
            }
        }
        assertEquals(emptyList<String>(), stale, "stale; regenerate with -Pbasedpython.regenerateUnreachableColors")
    }

    @Test
    fun `every shipped file is registered for its scheme`() {
        val pluginXml = File("src/main/resources/META-INF/plugin.xml").readText()
        for (entry in shipped) {
            assertTrue(
                "<additionalTextAttributes scheme=\"${entry.scheme}\" file=\"colorSchemes/unreachable/${entry.file}\"/>" in pluginXml,
                "${entry.scheme} is not registered",
            )
        }
    }

    @Test
    fun `a faded colour is the colour at VS Code's opacity over the background`() {
        val faded = ByUnreachableColors.fade(java.awt.Color(0xcf, 0x8e, 0x6d), java.awt.Color(0x1e, 0x1f, 0x22), ByUnreachableColors.DARK_OPACITY)
        assertEquals(java.awt.Color(0x94, 0x69, 0x54), faded)
    }
}
